import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';
import { CATS, DEFS, ICON, SIL, STAR_OFF, STAR_ON, TILES, catHead, catParts } from './m3v2-assets.mjs';
import { OBSTACLES, OBSTACLE_DEFS } from './obstacles.mjs';

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const artDir = join(projectRoot, 'game', 'art');
const ATLAS_WIDTH = 2048;
// Empty space around each sprite (in 2x pixels) so linear filtering never samples a neighbour.
const PAD = 8;

// Index + 1 is the tile kind used by the match-3 core: 1 food bowl, 2 yarn, 3 fish, 4 paw, 5 bell.
const TILE_KEYS = ['k-m', 'k-y', 'k-b', 'k-p', 'k-c'];
const BOOSTER_ICONS = { booster_row: 'lazer', booster_shuffle: 'nane', booster_single: 'pence' };
const CAT_FRAME = { w: 200, h: 264, viewBox: '0 0 100 132' };
const CAT_PIVOTS = {
  tail: [0.74, 118 / 132],
  body: [0.5, 124 / 132],
  head: [0.5, 76 / 132],
  blink: [0.5, 76 / 132],
};

const sprites = [];
const add = (name, w, h, viewBox, body, pivot = [0.5, 0.5]) => sprites.push({ name, w, h, viewBox, body, pivot });

TILE_KEYS.forEach((key, i) => add(`tile_${i + 1}`, 192, 192, '0 0 48 48', TILES[key]));
for (const [name, key] of Object.entries(BOOSTER_ICONS)) add(name, 128, 128, '0 0 48 48', ICON[key]);
add('star_on', 96, 96, '0 0 48 48', STAR_ON);
add('star_off', 96, 96, '0 0 48 48', STAR_OFF);
add('cat_silhouette', 200, 200, '0 0 100 100', SIL);
for (const [name, body] of Object.entries(OBSTACLES)) add(name, 192, 192, '0 0 48 48', body);
for (const cat of Object.keys(CATS)) {
  const parts = catParts(cat);
  add(`cat_${cat}_tail`, CAT_FRAME.w, CAT_FRAME.h, CAT_FRAME.viewBox, parts.tail, CAT_PIVOTS.tail);
  add(`cat_${cat}_body`, CAT_FRAME.w, CAT_FRAME.h, CAT_FRAME.viewBox, parts.shadow + parts.body, CAT_PIVOTS.body);
  add(`cat_${cat}_head`, CAT_FRAME.w, CAT_FRAME.h, CAT_FRAME.viewBox, parts.head, CAT_PIVOTS.head);
  add(`cat_${cat}_blink`, CAT_FRAME.w, CAT_FRAME.h, CAT_FRAME.viewBox, parts.blink, CAT_PIVOTS.blink);
  add(`cat_${cat}_face`, 200, 200, '0 0 100 100', catHead(cat));
}

function pack(list) {
  const placed = [...list].sort((a, b) => b.h - a.h || a.name.localeCompare(b.name));
  let x = PAD;
  let y = PAD;
  let rowHeight = 0;
  for (const s of placed) {
    if (x + s.w + PAD > ATLAS_WIDTH) {
      x = PAD;
      y += rowHeight + PAD;
      rowHeight = 0;
    }
    s.x = x;
    s.y = y;
    x += s.w + PAD;
    rowHeight = Math.max(rowHeight, s.h);
  }
  return { placed, height: Math.ceil((y + rowHeight + PAD) / 2) * 2 };
}

const { placed, height } = pack(sprites);
const inner = placed
  .map((s) => `<svg x="${s.x}" y="${s.y}" width="${s.w}" height="${s.h}" viewBox="${s.viewBox}">${s.body}</svg>`)
  .join('');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${ATLAS_WIDTH}" height="${height}" viewBox="0 0 ${ATLAS_WIDTH} ${height}"><defs>${DEFS}${OBSTACLE_DEFS}</defs>${inner}</svg>`;

const render = (width) =>
  new Resvg(svg, { fitTo: { mode: 'width', value: width }, font: { loadSystemFonts: false } }).render().asPng();

mkdirSync(artDir, { recursive: true });
writeFileSync(join(artDir, 'atlas_2x.png'), render(ATLAS_WIDTH));
writeFileSync(join(artDir, 'atlas_1x.png'), render(ATLAS_WIDTH / 2));

const rows = [...placed]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((s) => `\t"${s.name}": [${s.x}, ${s.y}, ${s.w}, ${s.h}, ${s.pivot[0].toFixed(4)}, ${s.pivot[1].toFixed(4)}],`);
const gd = `# Generated by tools/art/build.mjs; rerun the script instead of editing by hand.
class_name AtlasData
extends RefCounted

const WIDTH := ${ATLAS_WIDTH}
const HEIGHT := ${height}

# name: [x, y, w, h, pivot_x, pivot_y] in 2x pixels.
const SPRITES := {
${rows.join('\n')}
}
`;
writeFileSync(join(artDir, 'atlas_data.gd'), gd);

console.log(`atlas ${ATLAS_WIDTH}x${height} with ${placed.length} sprites`);
